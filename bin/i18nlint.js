#!/usr/bin/env node
'use strict';
/*
 * i18nlint — find the user-facing strings AI code tools hardcode instead of translating.
 * Part of Otto (dev.ottospace.co). Zero dependencies.
 * AI codegen ships English text baked into JSX, un-localized dates/currency, and no <html lang>.
 * i18nlint reports every one so nothing user-facing goes untranslated.
 */
const fs = require('fs');
const path = require('path');

const VERSION = '0.1.0';
const CODE_EXT = new Set(['.js', '.jsx', '.ts', '.tsx', '.html', '.vue', '.svelte', '.astro']);
const IGNORE_DIR = new Set(['node_modules', '.git', 'dist', 'build', '.next', 'out', 'coverage', '.turbo', 'vendor', '.svelte-kit']);
const L = 'A-Za-z\\u00C0-\\u024F\\u0600-\\u06FF'; // Latin (incl. accents) + Arabic

function lineOf(src, i) { return src.slice(0, i).split('\n').length; }

function scanFile(file, src) {
  const F = [];
  const push = (idx, from, msg) => F.push({ file, line: lineOf(src, idx), from: String(from).trim().replace(/\s+/g, ' ').slice(0, 60), msg });
  let m;

  // 1. Hardcoded JSX text nodes (text between tags containing real words)
  const t = new RegExp(`>([^<>{}]*[${L}]{2,}[^<>{}]*)<`, 'g');
  while ((m = t.exec(src))) {
    const txt = m[1].trim();
    if (!txt) continue;
    if (/^[\d\s.,:;!?%$€£+\-*/=()#|@·—–…'"]+$/.test(txt)) continue; // symbols/numbers only
    if (/^(https?:|\/\/|\.|@)/.test(txt)) continue;                 // urls / handles
    push(m.index + 1, txt, 'hardcoded UI text — wrap it in your i18n t()');
  }
  // 2. User-facing attributes with literal strings
  const a = new RegExp(`\\b(placeholder|title|alt|aria-label|label)\\s*=\\s*"([^"]*[${L}]{2,}[^"]*)"`, 'g');
  while ((m = a.exec(src))) push(m.index, `${m[1]}="${m[2]}"`, `hardcoded ${m[1]} text — move it to i18n`);
  // 3. toLocale* with no locale argument
  const l = /\.toLocale(String|DateString|TimeString)\(\s*\)/g;
  while ((m = l.exec(src))) push(m.index, m[0], `toLocale${m[1]}() with no locale — pass one (Intl)`);
  // 4. Hardcoded currency
  const c = /[$€£]\s?\d|\b\d[\d,.]*\s?(USD|EUR|GBP|SAR|AED|CAD|MAD)\b/g;
  while ((m = c.exec(src))) push(m.index, m[0], 'hardcoded currency — use Intl.NumberFormat(locale,{style:"currency"})');
  // 5. Missing lang on <html>
  const h = /<html\b(?![^>]*\blang=)[^>]*>/g;
  while ((m = h.exec(src))) push(m.index, '<html>', 'missing lang attribute on <html>');

  return F;
}

function walk(dir, out = []) {
  for (const name of fs.readdirSync(dir)) {
    if (IGNORE_DIR.has(name) || (name.startsWith('.') && name !== '.')) continue;
    const full = path.join(dir, name);
    let st; try { st = fs.statSync(full); } catch { continue; }
    if (st.isDirectory()) walk(full, out);
    else if (CODE_EXT.has(path.extname(full))) out.push(full);
  }
  return out;
}

const RULES_DOC = `# i18n rules for AI coding agents (generated by i18nlint)
1. Never hardcode user-facing text. Wrap every string a user reads in the project's translation function (t(), useTranslations(), <FormattedMessage>, $t()).
2. Localize user-facing attributes too: placeholder, title, alt, aria-label, label.
3. Never format dates/times/numbers by hand or with a bare toLocaleString(). Use Intl.DateTimeFormat / Intl.NumberFormat with an explicit locale.
4. Never hardcode currency symbols or amounts. Use Intl.NumberFormat(locale, { style: 'currency', currency }).
5. Set <html lang> (and dir) dynamically from the active locale.
`;

const HELP = `i18nlint v${VERSION} — find the user-facing strings AI code tools hardcode instead of translating.
Part of Otto · dev.ottospace.co

Usage:
  npx i18nlint [path]            report untranslated strings (default: .)
  npx i18nlint [path] --json     machine-readable output (CI)
  npx i18nlint [path] --init-rules  write I18N-RULES.md for your AI agent
  npx i18nlint --help | --version

i18nlint reports; it never edits — translating is a human decision (which key, which
message). It just makes sure nothing user-facing slips through untranslated.`;

function main() {
  const args = process.argv.slice(2);
  if (args.includes('--help') || args.includes('-h')) { console.log(HELP); return; }
  if (args.includes('--version') || args.includes('-v')) { console.log(VERSION); return; }
  const asJson = args.includes('--json');
  const target = args.find(a => !a.startsWith('-')) || '.';

  if (args.includes('--init-rules')) {
    const dest = path.join(target, 'I18N-RULES.md');
    fs.writeFileSync(dest, RULES_DOC);
    console.log(`✓ wrote ${dest} — point Cursor/Claude at it so they stop hardcoding strings.`);
    return;
  }

  let files;
  try { files = fs.statSync(target).isDirectory() ? walk(target) : [target]; }
  catch { console.error(`i18nlint: cannot read ${target}`); process.exit(2); }

  const byFile = {}; let total = 0;
  for (const file of files) {
    let src; try { src = fs.readFileSync(file, 'utf8'); } catch { continue; }
    const f = scanFile(file, src);
    if (f.length) { byFile[file] = f; total += f.length; }
  }
  const rel = f => path.relative(process.cwd(), f) || f;

  if (asJson) {
    console.log(JSON.stringify({ version: VERSION, files: files.length, findings: total,
      results: Object.entries(byFile).flatMap(([f, arr]) => arr.map(x => ({ ...x, file: rel(f) }))) }, null, 2));
    process.exit(total ? 1 : 0);
  }

  for (const file of Object.keys(byFile)) {
    console.log(`\n\x1b[1m${rel(file)}\x1b[0m`);
    for (const f of byFile[file]) console.log(`  \x1b[33mi18n\x1b[0m :${f.line}  ${f.from}  \x1b[2m${f.msg}\x1b[0m`);
  }
  console.log(`\n\x1b[1mi18nlint v${VERSION}\x1b[0m  ${files.length} files  ·  \x1b[33m${total} untranslated / un-localized\x1b[0m`);
  if (!total) console.log('✓ clean — nothing user-facing left hardcoded.');
  else console.log('→ wrap these in your i18n t(); run \x1b[1m--init-rules\x1b[0m so your AI agent stops adding them.');
  process.exit(total ? 1 : 0);
}

main();
