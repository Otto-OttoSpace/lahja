#!/usr/bin/env node
'use strict';
/*
 * lahja — find the user-facing strings AI code tools hardcode instead of translating.
 * (formerly i18nlint.) Part of Otto · dev.ottospace.co
 *
 * Detection is AST-verified (Babel for JS/TS/JSX/TSX) so live code — TS generics,
 * keys, ids, classNames, imports — is never mistaken for UI text. Markup bindings
 * (:placeholder, v-bind, bind:, {expr}) are never mistaken for literal text.
 * lahja REPORTS; it never edits. `--suggest` proposes a t()-wrap, applies nothing.
 */
const fs = require('fs');
const path = require('path');
const { scanSource, suggestFor } = require('../lib/lahja-core');

const VERSION = require('../package.json').version;

const CODE_EXT = new Set(['.js', '.jsx', '.ts', '.tsx', '.mjs', '.cjs', '.html', '.htm', '.vue', '.svelte', '.astro']);
const IGNORE_DIR = new Set(['node_modules', '.git', 'dist', 'build', '.next', 'out', 'coverage', '.turbo', 'vendor', '.svelte-kit']);
const BASELINE_FILE = '.lahja-baseline.json';
const IGNORE_FILE = '.lahjaignore';

// -- ignore file (.lahjaignore): substring / glob patterns of paths to skip -----
function loadIgnorePatterns(cwd) {
  const p = path.join(cwd, IGNORE_FILE);
  let raw; try { raw = fs.readFileSync(p, 'utf8'); } catch { return []; }
  return raw.split('\n').map(l => l.trim()).filter(l => l && !l.startsWith('#'))
    .map(g => new RegExp(g.replace(/[.+^${}()|[\]\\]/g, '\\$&').replace(/\*/g, '.*')));
}
function ignored(rel, patterns) { return patterns.some(re => re.test(rel)); }

function walk(dir, patterns, out = []) {
  let entries; try { entries = fs.readdirSync(dir); } catch { return out; }
  for (const name of entries) {
    if (IGNORE_DIR.has(name) || (name.startsWith('.') && name !== '.')) continue;
    const full = path.join(dir, name);
    let st; try { st = fs.statSync(full); } catch { continue; }
    if (st.isDirectory()) walk(full, patterns, out);
    else if (CODE_EXT.has(path.extname(full)) && !ignored(path.relative(process.cwd(), full), patterns)) out.push(full);
  }
  return out;
}

// -- baseline signature = file|rule|from (line-independent, survives shifts) ----
function sig(f) { return [f.file, f.rule, f.from].join('|'); }

const RULES_DOC = `# i18n rules for AI coding agents (generated by lahja)
1. Never hardcode user-facing text. Wrap every string a user reads in the project's translation function (t(), useTranslations(), <FormattedMessage>, $t()).
2. Localize user-facing attributes too: placeholder, title, alt, aria-label, label.
3. Never format dates/times/numbers by hand or with a bare toLocaleString(). Use Intl.DateTimeFormat / Intl.NumberFormat with an explicit locale.
4. Never hardcode currency symbols or amounts. Use Intl.NumberFormat(locale, { style: 'currency', currency }).
5. Set <html lang> (and dir) dynamically from the active locale.
6. Don't split, truncate, or measure text with split(' ') / .slice / .substring / .length or CSS word-break:break-all — those break no-space and complex scripts (Thai, Lao, Khmer, Myanmar, CJK, Indic, Arabic). Use Intl.Segmenter for word/grapheme boundaries.

Silence a deliberate exception with a \`// lahja-ignore\` comment on (or above) the line.
`;

const HELP = `lahja v${VERSION} — find the user-facing strings AI code tools hardcode instead of translating
(formerly i18nlint) · Part of Otto · dev.ottospace.co

Usage:
  npx lahja [path]              report untranslated strings (default: .)
  npx lahja [path] --json       machine-readable output (CI)
  npx lahja [path] --check      report only; exit non-zero if anything found (CI)
  npx lahja [path] --baseline   snapshot existing debt on first run, then fail only on NEW strings
  npx lahja [path] --update-baseline   (re)write the baseline from current findings
  npx lahja [path] --suggest    PROPOSE a t()-wrap for each finding (writes nothing)
  npx lahja [path] --init-rules write I18N-RULES.md for your AI agent
  npx lahja --help | --version

Ignoring: a \`// lahja-ignore\` comment on/above a line skips it; a \`.lahjaignore\`
file (glob/substring per line) skips whole paths.

lahja reports; it never edits — translating is a human decision (which key, which
message). AST-verified, so it never flags live code or dynamic bindings as UI text.`;

function main() {
  const args = process.argv.slice(2);
  if (args.includes('--help') || args.includes('-h')) { console.log(HELP); return; }
  if (args.includes('--version') || args.includes('-v')) { console.log(VERSION); return; }
  const asJson = args.includes('--json');
  // --check is accepted as a CI alias; report-only already exits 1 on any finding.
  const suggest = args.includes('--suggest');
  const useBaseline = args.includes('--baseline');
  const updateBaseline = args.includes('--update-baseline');
  const initRules = args.includes('--init-rules');
  const target = args.find(a => !a.startsWith('-')) || '.';

  if (initRules) {
    const dest = path.join(target, 'I18N-RULES.md');
    fs.writeFileSync(dest, RULES_DOC);
    console.log(`✓ wrote ${dest} — point Cursor/Claude at it so they stop hardcoding strings.`);
    return;
  }

  const patterns = loadIgnorePatterns(process.cwd());
  let files;
  try { files = fs.statSync(target).isDirectory() ? walk(target, patterns) : [target]; }
  catch { console.error(`lahja: cannot read ${target}`); process.exit(2); }

  const rel = f => path.relative(process.cwd(), f) || f;
  let all = [];
  for (const file of files) {
    let src; try { src = fs.readFileSync(file, 'utf8'); } catch { continue; }
    const { findings } = scanSource(file, src);
    for (const f of findings) all.push({ file: rel(file), ...f });
  }

  // -- baseline handling ------------------------------------------------------
  const baselinePath = path.join(process.cwd(), BASELINE_FILE);
  if (updateBaseline) {
    fs.writeFileSync(baselinePath, JSON.stringify(
      { version: VERSION, created: new Date().toISOString(), entries: all.map(sig).sort() }, null, 2) + '\n');
    console.log(`✓ wrote ${BASELINE_FILE} — ${all.length} findings snapshotted as accepted debt.`);
    return;
  }
  let baselineJustWritten = false;
  if (useBaseline) {
    let existing = null;
    try { existing = JSON.parse(fs.readFileSync(baselinePath, 'utf8')); } catch {}
    if (!existing) {
      fs.writeFileSync(baselinePath, JSON.stringify(
        { version: VERSION, created: new Date().toISOString(), entries: all.map(sig).sort() }, null, 2) + '\n');
      baselineJustWritten = true;
      console.log(`✓ wrote ${BASELINE_FILE} — ${all.length} existing findings accepted as debt. Future runs fail only on NEW strings.`);
      process.exit(0);
    }
    const known = new Set(existing.entries || []);
    all = all.filter(f => !known.has(sig(f)));
  }

  const total = all.length;
  const byFile = {};
  for (const f of all) (byFile[f.file] = byFile[f.file] || []).push(f);

  if (asJson) {
    console.log(JSON.stringify({ version: VERSION, files: files.length, findings: total,
      baseline: useBaseline || undefined,
      results: all.map(f => suggest ? { ...f, suggest: suggestFor(f) } : f) }, null, 2));
    process.exit(total ? 1 : 0);
  }

  for (const file of Object.keys(byFile)) {
    console.log(`\n\x1b[1m${file}\x1b[0m`);
    for (const f of byFile[file]) {
      console.log(`  \x1b[33mi18n\x1b[0m :${f.line}  ${f.from}  \x1b[2m${f.msg}\x1b[0m`);
      if (suggest) { const s = suggestFor(f); if (s) console.log(`       \x1b[36m→ suggest\x1b[0m  ${s}`); }
    }
  }
  const scope = useBaseline && !baselineJustWritten ? ' (new since baseline)' : '';
  console.log(`\n\x1b[1mlahja v${VERSION}\x1b[0m  ${files.length} files  ·  \x1b[33m${total} untranslated / un-localized${scope}\x1b[0m`);
  if (!total) console.log(useBaseline ? '✓ no new hardcoded strings since the baseline.' : '✓ clean — nothing user-facing left hardcoded.');
  else {
    console.log('→ wrap these in your i18n t(). Run \x1b[1m--suggest\x1b[0m to preview wraps, \x1b[1m--init-rules\x1b[0m so your AI agent stops adding them.');
    if (!useBaseline) console.log('   Adopting lahja on an existing project? \x1b[1m--baseline\x1b[0m accepts today\'s debt and fails only on NEW strings.');
  }
  process.exit(total ? 1 : 0);
}

main();
